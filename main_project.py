import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import List
from dotenv import load_dotenv
from faster_whisper import WhisperModel
from google import genai
from pydantic import BaseModel, Field

# Load API keys from .env file
load_dotenv()

# Initialize the modern Google GenAI Client
# It automatically picks up GEMINI_API_KEY from your environment variables
client = genai.Client()


# STEP 2 DEFINITION: Pydantic Data Structure

class ActionItem(BaseModel):
    task: str = Field(description="The specific task that needs to be done.")
    assignee: str = Field(description="The person responsible for this task. Use 'Unassigned' if unknown.")
    deadline: str = Field(description="The mentioned deadline, or 'Not specified'.")

class MeetingSummary(BaseModel):
    title: str = Field(description="A brief, catchy title for the meeting.")
    summary: str = Field(description="A high-level 3-4 sentence paragraph summarizing the meeting.")
    key_decisions: List[str] = Field(description="A list of the core decisions made during the meeting.")
    action_items: List[ActionItem] = Field(description="A list of actionable tasks assigned to individuals.")

# STEP 1: Audio Transcription (Remains Free & Local)

def transcribe_audio(audio_path: str) -> str:
    """Transcribes local audio files using faster-whisper (Runs locally for free)."""
    print("Step 1: Starting local transcription (this may take a moment)...")
    model = WhisperModel("base", device="cpu", compute_type="int8")
    segments, info = model.transcribe(audio_path, beam_size=5)

    full_transcript = []
    for segment in segments:
        full_transcript.append(segment.text)

    print("Step 1 Complete: Audio successfully transcribed.")
    return " ".join(full_transcript)


# STEP 2: Structured Analysis (Updated for Free Google Gemini)

def analyze_transcript(transcript_text: str) -> MeetingSummary:
    """Uses Google Gemini to enforce a strict JSON schema via Pydantic for free."""
    print("🔄 Step 2: Sending transcript to Google Gemini for structured analysis...")

    prompt = (
        f"You are an elite corporate assistant. Analyze the following meeting transcript. "
        f"Extract the high-level summary, key decisions, and explicit action items with assignees.\n\n"
        f"Transcript:\n{transcript_text}"
    )

    # We call gemini-2.5-flash which is fast, powerful, and free in AI Studio
    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=prompt,
        config={
            "response_mime_type": "application/json",
            "response_schema": MeetingSummary,  # Passes the Pydantic schema natively to Google
        },
    )

    print("✅ Step 2 Complete: Structured JSON data successfully generated by Gemini.")
    # The modern SDK parses the JSON directly into your Pydantic object automatically
    return response.parsed


# STEP 3: Business Automation (Emailing)

def send_summary_email(meeting_data: MeetingSummary, recipient_email: str):
    """Formats the structured JSON into HTML and emails it using standard SMTP."""
    print(f"🔄 Step 3: Formatting and sending email to {recipient_email}...")

    SMTP_SERVER = "://gmail.com"
    SMTP_PORT = 587
    SENDER_EMAIL = "your_test_email@gmail.com"
    SENDER_PASSWORD = "your_gmail_app_password"

    decisions_html = "".join([f"<li>{dec}</li>" for dec in meeting_data.key_decisions])
    actions_html = "".join([
        f"<tr>"
        f"<td style='padding:8px; border:1px solid #ddd;'><b>{item.assignee}</b></td>"
        f"<td style='padding:8px; border:1px solid #ddd;'>{item.task}</td>"
        f"<td style='padding:8px; border:1px solid #ddd; color:#888;'>{item.deadline}</td>"
        f"</tr>" for item in meeting_data.action_items
    ])

    html_content = f"""
    <html>
    <body style="font-family: Arial, sans-serif; color: #333; line-height: 1.6;">
        <h2 style="color: #1A73E8; border-bottom: 2px solid #1A73E8; padding-bottom: 8px;">📋 {meeting_data.title}</h2>

        <h3>Executive Summary</h3>
        <p>{meeting_data.summary}</p>

        <h3>🎯 Key Decisions</h3>
        <ul>{decisions_html}</ul>

        <h3>⚡ Action Items</h3>
        <table style="width:100%; border-collapse: collapse; margin-top: 10px;">
            <thead>
                <tr style="background-color: #F8F9FA; text-align: left;">
                    <th style="padding:8px; border:1px solid #ddd;">Who</th>
                    <th style="padding:8px; border:1px solid #ddd;">What</th>
                    <th style="padding:8px; border:1px solid #ddd;">Deadline</th>
                </tr>
            </thead>
            <tbody>
                {actions_html}
            </tbody>
        </table>
    </body>
    </html>
    """

    msg = MIMEMultipart("alternative")
    msg["Subject"] = f"Meeting Minutes: {meeting_data.title}"
    msg["From"] = SENDER_EMAIL
    msg["To"] = recipient_email
    msg.attach(MIMEText(html_content, "html"))

    try:
        with smtplib.SMTP(SMTP_SERVER, SMTP_PORT) as server:
            server.starttls()
            server.login(SENDER_EMAIL, SENDER_PASSWORD)
            server.sendmail(SENDER_EMAIL, recipient_email, msg.as_string())
        print("✅ Step 3 Complete: Professional email sent successfully!")
    except Exception as e:
        print(f"⚠️ Step 3 Note: Email transport skipped ({e}). Your structured data is verified!")


# MAIN EXECUTION PIPELINE

if __name__ == "__main__":
    AUDIO_FILE_PATH = "sample_meeting.mp3"
    MOCK_RECEIVER = "internship_manager@company.com"

    print("🚀 Starting Free Gemini Smart Meeting Assistant...\n")

    if not os.path.exists(AUDIO_FILE_PATH):
        print(f"❌ Error: Please place a dummy '{AUDIO_FILE_PATH}' file in this directory first.")
    else:
        transcript = transcribe_audio(AUDIO_FILE_PATH)
        print(f"\n--- Raw Transcript Snippet ---\n{transcript[:200]}...\n")

        structured_data = analyze_transcript(transcript)
        print(f"\n--- Clean Gemini JSON Output ---\n{structured_data.model_dump_json(indent=2)}\n")

        send_summary_email(structured_data, recipient_email=MOCK_RECEIVER)
        print("\n🎉 Pipeline Execution Finished Successfully!")
